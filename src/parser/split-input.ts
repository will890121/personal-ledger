/**
 * 把一則訊息切成多筆交易。**只有換行是分隔符。**
 *
 * 2026-10-02 之前，分隔符是 `[,，、\n]`，而那造成兩個問題：
 *
 * 1. 半形 `,` 同時是中文數字的千分位符號，所以「薪水 +85,000」被拆成「薪水 +85」與
 *    「000」兩筆——兩筆都是看起來合法的輸入，不會報錯。千分位是記帳時會自然打出來的
 *    寫法，這是真實的資料正確性問題，不是邊角案例。
 * 2. 全形 `，` 同時代表兩件相反的事：「午餐 1260，小明欠 630」是**一筆**交易的分帳明細，
 *    「午餐 120，Uber 245」是**兩筆**交易。為了分辨它們，這裡曾經有一組啟發式
 *    （沒有金額的段落併回上一段、純欠款子句併回上一段、第一段沒有金額就併進第二段），
 *    佔了這個檔案一半以上的篇幅，而它們在做的事就是把剛才切錯的東西黏回去。
 *
 * 換行沒有這兩個歧義：它不會出現在數字中間，也不會出現在一行之內。於是「一行一筆、
 * 分帳寫在同一行」成為明確的規則，整組啟發式可以刪掉。
 *
 * **刻意不保留任何合併邏輯。** 使用者換行了，就是明確說「這是分開的」；再用啟發式去
 * 推翻那個意圖，等於把剛拿掉的猜測搬到另一個地方。沒有金額的那一行會變成一張缺欄位的
 * 草稿——看得見、可取消，而不是一筆默默記錯的帳。
 *
 * 若使用者的 Enter 鍵是直接送出而非換行，多筆輸入會自然降級成「一則訊息一筆」，
 * 帳本結果相同，只是少了批次確認的便利。
 */
export function splitInput(text: string): string[] {
  return text
    .split("\n")
    .map((segment) => segment.trim())
    .filter((segment) => segment.length > 0);
}
