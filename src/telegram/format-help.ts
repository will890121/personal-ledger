import { LEDGER_COMMANDS } from "./commands.js";

/**
 * `/help` 的版面：先示範怎麼打字，指令清單放在最後。
 *
 * 這個 bot 的主要介面是自由文字，不是指令——使用者三個月後會忘記的是句子怎麼寫，
 * 不是總共有哪八個指令，而且真正容易忘記的往往是最少打的那幾種句法（日期前綴、
 * 平分、回收款、一句多筆），不是每天都打的「午餐 120」。把輸入範例放在最前面、
 * 分成「記一筆／分帳與代墊／一次多筆」三段各自涵蓋一種語法，讓真正會被遺忘的
 * 東西先被看到，並且每一種都至少出現一次。
 *
 * 指令段落由 LEDGER_COMMANDS 展開，不手動抄一份：這份清單同時也是
 * setMyCommands 的參數與 handler 註冊的依據，三者永遠一致。
 */
export function formatHelp(): string {
  const commandLines = LEDGER_COMMANDS.map(
    ({ command, description }) => `/${command} - ${description}`,
  ).join("\n");

  return [
    "直接打字就能記帳，不需要先學指令：",
    "",
    "記一筆",
    "午餐 120",
    "薪水 +85000",
    "昨天 Uber 245 國泰卡",
    "台新轉國泰 5000 手續費 15",
    "",
    "分帳與代墊",
    "午餐 1260，小明欠 630",
    "午餐 1000，三個人平分",
    "小明還 300",
    "",
    "一次多筆（換行分隔，一行一筆）",
    "午餐 120",
    "Uber 245",
    "",
    "金額前面加「+」代表收入，不加符號預設是支出；日期前面可以加「昨天」；",
    "用「，...欠...」或「...平分」記代墊或分帳，之後可以用 /advances 查還沒收回的部分，",
    "「某人還 N」用來記錄收回代墊款。",
    "一次記多筆要用換行分隔——分帳的「，」寫在同一行，不會被當成下一筆。",
    "",
    "指令：",
    commandLines,
  ].join("\n");
}
